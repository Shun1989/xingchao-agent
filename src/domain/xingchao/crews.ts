export const crews: CrewProfile[] = seeds.map(({ members, ...crew }) => ({
  ...crew,
  captainId: members[0].id,
  memberIds: members.map((member) => member.id),
}))

export const agents: AgentProfile[] = seeds.flatMap((crew) =>
  crew.members.map((member, index) => agentFromSeed(member, crew, index)),
)

export const crewById = new Map<CrewId, CrewProfile>(crews.map((crew) => [crew.id, crew]))
export const agentById = new Map(agents.map((agent) => [agent.id, agent]))

export function agentsForCrew(crewId: CrewId): AgentProfile[] {
  return agents.filter((agent) => agent.crewId === crewId)
}
